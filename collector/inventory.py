"""Station inventory: machine file (data/stations.json), table (data/stations.csv) and STATIONS.md."""

from __future__ import annotations

import csv
import json
from dataclasses import asdict
from statistics import median

from .common import DATA, ROOT, SAL, SPCOND, TEMP, Station, distance_m, iso

JSON_PATH = DATA / "stations.json"
CSV_PATH = DATA / "stations.csv"
MD_PATH = ROOT / "STATIONS.md"

# When two stations from different systems sit within DUP_METRES and measure the same thing,
# the one from the later system here is flagged as a possible duplicate (both are still kept).
SYSTEM_PRIORITY = ["coops", "usgs", "erddap-gcoos", "erddap-secoora", "erddap-ioos", "ndbc"]
DUP_METRES = 300


def load() -> tuple[list[Station], dict]:
    if not JSON_PATH.exists():
        return [], {}
    j = json.loads(JSON_PATH.read_text())
    stations = [Station(**s) for s in j.get("stations", [])]
    return stations, j


def flag_duplicates(stations: list[Station]) -> None:
    pri = {s: i for i, s in enumerate(SYSTEM_PRIORITY)}
    for st in stations:
        st.possible_duplicate_of = ""
    for a in stations:
        for b in stations:
            if a is b or a.system == b.system:
                continue
            if pri.get(a.system, 99) >= pri.get(b.system, 99):
                continue
            if not set(a.variables) & set(b.variables):
                continue
            if distance_m(a.lat, a.lon, b.lat, b.lon) <= DUP_METRES:
                if not b.possible_duplicate_of:
                    b.possible_duplicate_of = a.uid


def update_cadence(stations: list[Station], readings) -> None:
    times: dict[str, set] = {}
    for r in readings:
        if r.variable == TEMP or r.variable == SAL:
            times.setdefault(r.station_uid, set()).add(r.time)
    for st in stations:
        ts = sorted(times.get(st.uid, ()))
        if len(ts) >= 3:
            gaps = [(b - a).total_seconds() / 60 for a, b in zip(ts, ts[1:])]
            st.cadence_min = round(median(gaps), 1)
        if ts:
            newest = iso(ts[-1])
            if newest > (st.last_obs or ""):
                st.last_obs = newest


def update_depths(stations: list[Station], readings) -> None:
    seen: dict[str, set] = {}
    for r in readings:
        label = r.depth_tag if r.depth_m is None else f"{r.depth_tag} {r.depth_m:g} m"
        seen.setdefault(r.station_uid, set()).add(label)
    for st in stations:
        if st.uid in seen:
            st.depths = sorted(seen[st.uid])


def save(stations: list[Station], meta: dict) -> None:
    stations = sorted(stations, key=lambda s: (not s.collect, s.provider, s.name))
    out = dict(meta)
    out["stations"] = [asdict(s) for s in stations]
    JSON_PATH.parent.mkdir(parents=True, exist_ok=True)
    JSON_PATH.write_text(json.dumps(out, indent=1, sort_keys=False) + "\n")

    cols = ["station_uid", "provider", "source_system", "station_id", "name", "lat", "lon",
            "in_area", "edge_anchor", "collected", "active", "last_obs_utc", "cadence_min", "depths",
            "measures_temp", "measures_salinity", "measures_spec_cond", "possible_duplicate_of", "url", "notes"]
    with open(CSV_PATH, "w", newline="") as f:
        w = csv.writer(f, lineterminator="\n")
        w.writerow(cols)
        for s in stations:
            w.writerow([s.uid, s.provider, s.system, s.station_id, s.name, f"{s.lat:.5f}", f"{s.lon:.5f}",
                        yn(s.in_area), yn(s.edge_anchor), yn(s.collect), yn(s.active), s.last_obs,
                        "" if s.cadence_min is None else s.cadence_min, "; ".join(map(str, s.depths)),
                        yn(TEMP in s.variables), yn(SAL in s.variables), yn(SPCOND in s.variables),
                        s.possible_duplicate_of, s.url, s.notes])
    write_markdown(stations, meta)


def yn(b: bool) -> str:
    return "yes" if b else "no"


def write_markdown(stations: list[Station], meta: dict) -> None:
    collected = [s for s in stations if s.collect]
    active = [s for s in collected if s.active]
    sal = [s for s in active if SAL in s.variables or SPCOND in s.variables]
    lines = [
        "# Station inventory",
        "",
        "Generated by the collector. Do not edit by hand: it is rewritten whenever stations are rediscovered",
        "(once a day). The full table, with URLs and notes, is in [data/stations.csv](data/stations.csv).",
        "",
        f"Last discovery: {meta.get('discovered', 'unknown')}.",
        "",
        f"- Stations inside the study area or kept as edge anchors: **{len(collected)}**",
        f"- Active (reported in the last {meta.get('active_within_days', 14)} days): **{len(active)}**",
        f"- Active stations that measure salinity or conductance: **{len(sal)}**",
        "",
        "Depth: `surface` means near-surface or a single sensor assumed near-surface. Cadence is the median",
        "gap between readings in the latest pull, in minutes. Temperature is stored in degrees C and salinity",
        "in PSU; the map converts temperature to degrees F for display.",
        "",
    ]
    by_provider: dict[str, list[Station]] = {}
    for s in collected:
        by_provider.setdefault(s.provider, []).append(s)
    lines += ["## By provider", "", "| Provider | Stations | Active | With salinity |", "|---|---:|---:|---:|"]
    for p, ss in sorted(by_provider.items(), key=lambda kv: -len(kv[1])):
        a = [s for s in ss if s.active]
        lines.append(f"| {p} | {len(ss)} | {len(a)} | {sum(1 for s in a if SAL in s.variables or SPCOND in s.variables)} |")
    lines += ["", "## Collected stations", "",
              "| Station | Provider | ID | Lat | Lon | Active | Cadence (min) | Depths | Temp | Salinity | Note |",
              "|---|---|---|---:|---:|---|---:|---|---|---|---|"]
    for s in sorted(collected, key=lambda s: (-s.lat)):
        note = []
        if s.edge_anchor:
            note.append("edge anchor outside area")
        if s.possible_duplicate_of:
            note.append(f"possible duplicate of {s.possible_duplicate_of}")
        salinity = "yes" if SAL in s.variables else ("conductance" if SPCOND in s.variables else "no")
        lines.append(
            f"| [{esc(s.name)}]({s.url}) | {esc(s.provider)} | `{s.uid}` | {s.lat:.4f} | {s.lon:.4f} | "
            f"{yn(s.active)} | {'' if s.cadence_min is None else s.cadence_min} | {esc(', '.join(map(str, s.depths)))} | "
            f"{yn(TEMP in s.variables)} | {salinity} | {'; '.join(note)} |")
    outside = [s for s in stations if not s.collect]
    if outside:
        lines += ["", "## Found in the bounding box but not collected", "",
                  "These are outside the area polygon (mostly the Atlantic side of the Keys). Add a station's ID to",
                  "`edge_anchors` in `config/area.json` to collect it. Several are freshwater canals on the Miami side.", "",
                  "| Station | Provider | ID | Lat | Lon | Active |", "|---|---|---|---:|---:|---|"]
        for s in sorted(outside, key=lambda s: -s.lat):
            act = yn(s.active) if s.last_obs else "not checked"
            lines.append(f"| {esc(s.name)} | {esc(s.provider)} | `{s.uid}` | {s.lat:.4f} | {s.lon:.4f} | {act} |")
    mirrors = meta.get("skipped_mirrors", [])
    if mirrors:
        lines += ["", "## Mirrors skipped", "",
                  f"{len(mirrors)} dataset entries were skipped because they repeat a station already pulled from its",
                  "owner (for example NDBC copies of Everglades National Park and CO-OPS stations, or SECOORA",
                  "copies of USGS gages). They are listed in `data/stations.json` under `skipped_mirrors`."]
    MD_PATH.write_text("\n".join(lines) + "\n")


def esc(x: str) -> str:
    return str(x).replace("|", "/")
